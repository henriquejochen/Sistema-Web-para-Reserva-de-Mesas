-- Modelo do banco (PostgreSQL) — Sistema de Reserva de Mesas
-- Referência/documentação. A fonte oficial é a migração Django
-- backend/reservas/migrations/0001_initial.py: para criar o banco use
--   python manage.py migrate
-- (o migrate também cria as tabelas internas do Django: usuários, sessões etc.)

CREATE TABLE reservas_mesa (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero        INTEGER     NOT NULL UNIQUE CHECK (numero >= 0),
    capacidade    INTEGER     NOT NULL CHECK (capacidade >= 0),
    area          VARCHAR(10) NOT NULL DEFAULT 'interna',      -- interna | externa
    ativa         BOOLEAN     NOT NULL DEFAULT TRUE,             -- RN04/RF10: inativa não recebe reservas
    situacao      VARCHAR(12) NOT NULL DEFAULT 'disponivel',   -- disponivel | reservada | ocupada
    criado_em     TIMESTAMPTZ NOT NULL,
    atualizado_em TIMESTAMPTZ NOT NULL
);

CREATE TABLE reservas_reserva (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(120) NOT NULL,
    telefone              VARCHAR(20)  NOT NULL,                -- só dígitos, com DDD
    pessoas               INTEGER      NOT NULL CHECK (pessoas >= 0),
    data                  DATE         NOT NULL,                -- disponibilidade é por dia (RN15)
    previsao_chegada      TIME         NOT NULL,                -- só para recepção e atraso (RN22)
    area                  VARCHAR(10)  NOT NULL DEFAULT 'qualquer', -- preferência: interna | externa | qualquer
    observacao            TEXT         NOT NULL DEFAULT '',
    status                VARCHAR(20)  NOT NULL DEFAULT 'confirmada', -- confirmada | presente | cancelada | concluida | nao_compareceu
    motivo_cancelamento   VARCHAR(120) NOT NULL DEFAULT '',
    codigo                VARCHAR(16)  NOT NULL UNIQUE,         -- código curto (RN17), não dá acesso
    token                 VARCHAR(64)  NOT NULL UNIQUE,         -- link exclusivo do cliente (RF06)
    chave_idempotencia    VARCHAR(64)  NULL UNIQUE,             -- evita reserva duplicada em reenvio
    assinatura_requisicao VARCHAR(64)  NOT NULL DEFAULT '',
    chegada_confirmada_em TIMESTAMPTZ  NULL,                    -- RF14
    concluido_em          TIMESTAMPTZ  NULL,
    criado_em             TIMESTAMPTZ  NOT NULL,                -- RNF13
    atualizado_em         TIMESTAMPTZ  NOT NULL,
    cancelado_em          TIMESTAMPTZ  NULL
);
CREATE INDEX reservas_re_data_9268de_idx ON reservas_reserva (data, status);

-- Mesa(s) atribuída(s) a cada reserva. Grupos maiores que a maior mesa recebem mais de uma mesa da mesma área.
CREATE TABLE reservas_reservamesa (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT  NOT NULL REFERENCES reservas_reserva (id) ON DELETE CASCADE,
    mesa_id    BIGINT  NOT NULL REFERENCES reservas_mesa (id),   -- PROTECT: mesa com histórico não é apagada (RN18)
    data       DATE    NOT NULL,
    ativa      BOOLEAN NOT NULL DEFAULT TRUE,                       -- falso quando a reserva é cancelada/concluída
    CONSTRAINT reserva_mesa_unica UNIQUE (reserva_id, mesa_id)
);
-- RN01 / RNF12: uma mesa não pode ter duas reservas ativas no mesmo dia, mesmo com pedidos simultâneos.
CREATE UNIQUE INDEX mesa_ativa_unica_dia ON reservas_reservamesa (mesa_id, data) WHERE ativa;
CREATE INDEX reservas_reservamesa_reserva_id ON reservas_reservamesa (reserva_id);
CREATE INDEX reservas_reservamesa_mesa_id ON reservas_reservamesa (mesa_id);
